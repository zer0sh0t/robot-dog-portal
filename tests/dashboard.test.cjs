const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const elements=new Map([...html.matchAll(/id="([^"]+)"/g)].map(m=>[m[1],{textContent:'',dataset:{}}]));
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1].replace('poll();','');
const context={document:{getElementById:id=>elements.get(id)},setInterval(){},setTimeout(){}};
vm.createContext(context);vm.runInContext(script,context);
const reading=(value,unit)=>({value,unit,fresh:true,age_s:0});
const sensors={alarm:'clear',smoke:reading(0,'raw'),temperature:reading(25,'°C'),fire_alert:reading(false)};
context.renderSensors(sensors);
assert.equal(elements.get('alarm-state').textContent,'NO FIRE ALERT');
assert.equal(elements.get('smoke-value').textContent,'0.0 raw');
context.renderSensors({...sensors,alarm:'active',fire_alert:reading(true)});
assert.equal(elements.get('alarm-state').textContent,'FIRE ALERT');
context.renderSensors({...sensors,alarm:'unknown',temperature:{value:25,fresh:false,unit:'°C'}});
assert.equal(elements.get('temperature-value').textContent,'–');
assert.match(elements.get('temperature-status').textContent,/Stale/);
context.renderSensors(sensors,false);
assert.equal(elements.get('alarm-state').textContent,'ALARM STATE UNKNOWN');
assert.equal(elements.get('smoke-value').textContent,'–');
context.renderSensors(undefined);
assert.equal(elements.get('alarm-state').textContent,'ALARM STATE UNKNOWN');
console.log('Dashboard render checks passed');
